"""Write the held-out train selection (configs/heldout_split.json) into the RL configs,
between the `# BEGIN heldout-train-select` / `# END heldout-train-select` markers.

    python3 scripts/apply_split.py
"""

import json
import re
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGETS = [ROOT / "configs" / "wordle" / name for name in ("rl.toml", "rl_lora.toml", "rl_turns.toml", "rl_cot.toml")]
BLOCK = re.compile(r"(# BEGIN heldout-train-select\n).*?(# END heldout-train-select)", re.S)


def main() -> None:
    split = json.loads((ROOT / "configs" / "heldout_split.json").read_text())
    start, stop = split["train_range"]
    excluded = split["excluded_train_seeds"]
    body = (
        f"# Seeds {start}-{stop - 1} minus the {len(excluded)} whose secret word is one of the "
        f"{len(split['held_out_words'])} eval words\n"
        f"# (generated by scripts/make_split.py; prime-rl cycles this finite list in order).\n"
        f'select.include.idx = ["{start}:{stop}"]\n'
        "select.exclude.idx = [\n"
        + textwrap.fill(", ".join(map(str, excluded)), width=96, initial_indent="  ", subsequent_indent="  ")
        + ",\n]\n"
    )
    for path in TARGETS:
        text = path.read_text()
        new, n = BLOCK.subn(lambda m: m.group(1) + body + m.group(2), text)
        if n != 1:
            raise SystemExit(f"{path}: expected one heldout-train-select block, found {n}")
        path.write_text(new)
        print(f"updated {path.relative_to(ROOT)} ({len(excluded)} excluded seeds)")


if __name__ == "__main__":
    main()
